// Package go2rtc implements ports.StreamEngine on top of a supervised go2rtc
// process (https://github.com/AlexxIT/go2rtc).
//
// Responsibilities:
//   - render go2rtc's YAML config from the domain cameras (config.go)
//   - run and restart the go2rtc process (supervisor.go)
//   - query go2rtc's HTTP API for stream status (client.go)
//   - expose go2rtc's player endpoints through a reverse proxy (proxy.go)
//   - pause/resume cameras by re-rendering the config and restarting
//     go2rtc (engine.go)
package go2rtc

import (
	"bytes"
	"fmt"
	"net/url"
	"sort"
	"strings"
	"text/template"

	"github.com/maikomr/watchmydog/internal/domain"
)

// Settings are the engine-level knobs (see config.Engine).
type Settings struct {
	Bin        string
	APIAddr    string
	RTSPAddr   string
	WebRTCPort int
	FFmpegBin  string
	CaptureBin string
	LogLevel   string
}

// RenderConfig produces go2rtc's YAML for the given cameras.
//
// Video: wmd-capture (native AVFoundation, ADR-0004) pipes raw NV12 into
// ffmpeg, which hardware-encodes H.264 and pushes RTSP into go2rtc.
// Audio: go2rtc's own ffmpeg device source, transcoded to Opus for WebRTC.
func RenderConfig(s Settings, cameras []domain.Camera) ([]byte, error) {
	sorted := append([]domain.Camera(nil), cameras...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].ID < sorted[j].ID })

	type stream struct {
		Name    string
		Sources []string
	}
	var streams []stream
	for _, c := range sorted {
		st := stream{Name: string(c.ID), Sources: []string{videoSource(s, c)}}
		if c.HasAudio() {
			st.Sources = append(st.Sources, audioSource(c))
		}
		streams = append(streams, st)
	}

	var buf bytes.Buffer
	err := configTmpl.Execute(&buf, map[string]any{
		"Settings": s,
		"Streams":  streams,
	})
	if err != nil {
		return nil, fmt.Errorf("render go2rtc config: %w", err)
	}
	return buf.Bytes(), nil
}

// videoSource builds the exec: source for a camera's video.
func videoSource(s Settings, c domain.Camera) string {
	v := c.Video
	cmd := fmt.Sprintf(
		`%s run --device %s --width %d --height %d --fps %d | %s -hide_banner -loglevel error`+
			` -f rawvideo -pix_fmt nv12 -video_size %dx%d -framerate %d -i pipe:0`+
			` -c:v h264_videotoolbox -realtime 1 -b:v %dk -g %d -bf 0 -profile:v main`+
			` -rtsp_transport tcp -f rtsp {output}`,
		shellQuote(s.CaptureBin), shellQuote(v.Device), v.Width, v.Height, v.FPS,
		shellQuote(s.FFmpegBin),
		v.Width, v.Height, v.FPS,
		v.BitrateKbps, 2*v.FPS,
	)
	// go2rtc splits the exec line itself (no shell), so the pipeline runs
	// under sh -c. killsignal/killtimeout let go2rtc stop it cleanly.
	return fmt.Sprintf(`exec:sh -c %s#killsignal=15#killtimeout=5`, shellQuoteDouble(cmd))
}

// audioSource builds the ffmpeg:device source for a camera's audio.
func audioSource(c domain.Camera) string {
	return "ffmpeg:device?audio=" + url.QueryEscape(c.Audio.Device) + "#audio=opus"
}

// shellQuote wraps s in single quotes for sh.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// shellQuoteDouble wraps s in double quotes for go2rtc's own argument
// splitter, which understands double quotes but not single ones at the
// top level. Inner double quotes are escaped.
func shellQuoteDouble(s string) string {
	return `"` + strings.ReplaceAll(s, `"`, `\"`) + `"`
}

var configTmpl = template.Must(template.New("go2rtc").Funcs(template.FuncMap{
	"yamlString": yamlString,
}).Parse(`# Generated by watchmydog. Do not edit; change watchmydog's config instead.
api:
  listen: {{yamlString .Settings.APIAddr}}
rtsp:
  listen: {{yamlString .Settings.RTSPAddr}}
webrtc:
  listen: ":{{.Settings.WebRTCPort}}"
ffmpeg:
  bin: {{yamlString .Settings.FFmpegBin}}
log:
  level: {{.Settings.LogLevel}}
  exec: debug
streams:
{{- range .Streams}}
  {{.Name}}:
{{- range .Sources}}
    - {{yamlString .}}
{{- end}}
{{- end}}
{{- if not .Streams}} {}{{end}}
`))

// yamlString renders s as a double-quoted YAML scalar.
func yamlString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`)
	return `"` + r.Replace(s) + `"`
}
